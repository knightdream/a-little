#!/usr/bin/env python3
"""Prepare the existing Hydrowing/Wing simplified Chinese translation (GBK)."""
import hashlib
import re
import shutil
import urllib.request
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
URL = 'https://www.cavestory.one/downloads/dou_sc102.zip'
SHA256 = 'd1e632a8f88cbd704ad300a27fd74abe2ada8faa67789d2274dd8ef8fee4df1e'
archive = ROOT / '.local/downloads/dou_sc102.zip'
archive.parent.mkdir(parents=True, exist_ok=True)
if not archive.exists():
    with urllib.request.urlopen(URL, timeout=60) as response:
        archive.write_bytes(response.read())
if hashlib.sha256(archive.read_bytes()).hexdigest() != SHA256:
    raise SystemExit('Chinese archive checksum mismatch')
output = ROOT / 'game_chinese'
output.mkdir(exist_ok=True)
# Keep upstream font/music resources that the original Windows executable embedded.
shutil.copytree(ROOT / 'game_english/data', output / 'data', dirs_exist_ok=True)
with zipfile.ZipFile(archive) as z:
    for entry in z.infolist():
        if entry.filename.startswith('Doukutsu/data/') and not entry.is_dir():
            relative = Path(entry.filename).relative_to('Doukutsu')
            if '..' in relative.parts:
                raise SystemExit('Unsafe archive path')
            target = output / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(z.read(entry))
    (output / '汉化原始说明.txt').write_text(z.read('Doukutsu/Readme.txt').decode('gbk'), encoding='utf-8')
    exe = z.read('Doukutsu/Doukutsu.exe')
# The original stage table has 95 records, each 200 bytes; keep all gameplay fields
# from CSE2 and extract only translated names, checking the map ID of every record.
start = exe.index(b'Pens\0' + b'\0' * 27 + b'Pens1\0') - 200
source = (ROOT / 'src/Stage.cpp').read_text()
entries = re.findall(r'^\s*STAGE_ENTRY\((.*)\),?.*$', source, re.M)
assert len(entries) == 95, len(entries)
lines = ['// Generated by scripts/prepare_chinese.py; names from dou_sc102 (see translation credits).']
for i, entry in enumerate(entries):
    record = exe[start + i * 200:start + (i + 1) * 200]
    map_id = re.match(r'"[^"]*",\s*"([^"]*)"', entry).group(1)
    assert record[32:64].split(b'\0')[0].decode('ascii').lower() == map_id.lower(), (i, map_id, record[32:64])
    name = record[165:197].split(b'\0')[0]
    name.decode('gbk')  # fail rather than accepting an incorrectly located table
    fields = entry.split(',', 7)[:7]
    literal = '"' + ''.join('\\x%02X' % b for b in name) + '"'
    lines.append('{' + ','.join(fields) + ', ' + literal + '},')
(ROOT / 'src/StageChinese.inc').write_text('\n'.join(lines) + '\n')
print('Prepared simplified Chinese assets and all 95 map names in', output)
